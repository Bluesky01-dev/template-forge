import { mkdir, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { SiteDoc, TemplateManifest } from "@tf/schema";

/**
 * Ingested templates live as JSON in packages/templates/src/ingested/<id>.json
 * and are registered through a generated index.ts (re-written on every import).
 */
export async function writeTemplate(dir: string, manifest: TemplateManifest, doc: SiteDoc): Promise<string> {
  await mkdir(dir, { recursive: true });
  const file = join(dir, `${manifest.id}.json`);
  await writeFile(file, JSON.stringify({ manifest, site: doc }, null, 2) + "\n");
  await regenerateIndex(dir);
  return file;
}

export async function regenerateIndex(dir: string) {
  const ids = (await readdir(dir)).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
  const ident = (id: string) => `t_${id.replace(/[^a-zA-Z0-9]/g, "_")}`;
  const src = `// AUTO-GENERATED by @tf/ingest — do not edit by hand.
${ids.map((id) => `import ${ident(id)} from "./${id}.json";`).join("\n")}

export const ingested: Array<{ manifest: unknown; site: unknown }> = [${ids.map(ident).join(", ")}];
`;
  await writeFile(join(dir, "index.ts"), src);
}
